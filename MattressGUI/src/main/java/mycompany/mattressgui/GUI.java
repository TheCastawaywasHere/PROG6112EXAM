    private void BtnProcessActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnProcessActionPerformed
       try {
        // Get inputs
        String customerName = TextCustomer.getText().trim();
        String productName = ComboItem.getSelectedItem().toString();
        double price = Double.parseDouble(TextPrice.getText());

        // Calculate VAT and commission
        double vat = price * 0.15;
        double commission = price * 0.05;
        double total = price + vat + commission;

        // Build message (no original price shown)
        String message = String.format(
                "Customer: %s\nProduct: %s\n\nVAT: %.2f\nCommission: %.2f\n-----------------\nTotal: %.2f",
                customerName, productName, vat, commission, total
        );

        // Show popup
        JOptionPane.showMessageDialog(this, message, "Message", JOptionPane.INFORMATION_MESSAGE);

    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
                "Please enter a valid numeric price.",
                "Invalid Input",
                JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BtnProcessActionPerformed

